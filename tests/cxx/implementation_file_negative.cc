// Tests files that a header #includes, but that are not implementation
// files of that header: they must be treated as usual.  If they were taken
// for implementation files, they would be private to
// implementation_file_negative-d1.h, and this file would be told to
// #include that header instead of them.

#include "tests/cxx/implementation_file_negative-d1.h"
#include "tests/cxx/implementation_file_negative-i6.h"

void Use() {
  // Defined in -i1.h, after a forward declaration in -d1.h.
  // IWYU: NegFwdThenDefined is...*implementation_file_negative-i1.h
  NegFwdThenDefined f;
  // Defined in -i2.h, which relies on -d1.h for IndirectClass.
  // IWYU: NegUsesIndirect(int) is...*implementation_file_negative-i2.h
  NegUsesIndirect(1);
  // An enumerator generated by the X-macro file -i4.def.
  int color = NegRed;
  // Defined in -d1.h by a macro from -i3.h.
  NegCreate();
  // IWYU: NEG_ZERO is...*implementation_file_negative-i3.h
  int zero = NEG_ZERO;
  // Defined in -i5.h, after a forward declaration in -d1.h.
  // IWYU: NegNode is...*implementation_file_negative-i5.h
  NegNode node;
  // Defined in -i6.h, which this file #includes too.
  NegLog("message");
}

